const LANG_NAMES = { en: "English", tr: "Turkce", de: "Deutsch", fr: "Francais", es: "Espanol" };

// ---- State ----
let currentLang = localStorage.getItem("tvbp_lang") || "en";

// ---- Language switcher ----
function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem("tvbp_lang", lang);
  document.documentElement.lang = lang;

  // Update all translatable elements
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (T[lang] && T[lang][key]) {
      el.textContent = T[lang][key];
    }
  });

  // Update lang button text
  const btn = document.querySelector(".lang-btn-text");
  if (btn) btn.textContent = LANG_NAMES[lang] || lang;

  // Update active state in dropdown
  document.querySelectorAll(".lang-option").forEach(opt => {
    opt.classList.toggle("active", opt.getAttribute("data-lang") === lang);
  });

  // Close dropdown
  const dd = document.querySelector(".lang-dropdown");
  if (dd) dd.classList.remove("open");
}

// ---- Mobile menu ----
function toggleMenu() {
  const nav = document.querySelector(".nav");
  if (nav) nav.classList.toggle("open");
}

// ---- Accordion ----
function initAccordion() {
  document.querySelectorAll(".accordion-btn").forEach(btn => {
    btn.addEventListener("click", () => {
      const item = btn.closest(".accordion-item");
      const body = item.querySelector(".accordion-body");
      const isOpen = item.classList.contains("open");

      // Close all
      document.querySelectorAll(".accordion-item").forEach(ai => {
        ai.classList.remove("open");
        ai.querySelector(".accordion-body").style.maxHeight = null;
      });

      // Open clicked if it was closed
      if (!isOpen) {
        item.classList.add("open");
        body.style.maxHeight = body.scrollHeight + "px";
      }
    });
  });
}

// ---- Init ----
document.addEventListener("DOMContentLoaded", () => {
  // Language dropdown toggle
  const langBtn = document.querySelector(".lang-btn");
  const langDd = document.querySelector(".lang-dropdown");
  if (langBtn && langDd) {
    langBtn.addEventListener("click", (e) => {
      e.stopPropagation();
      langDd.classList.toggle("open");
    });
    document.addEventListener("click", () => langDd.classList.remove("open"));
    langDd.addEventListener("click", (e) => e.stopPropagation());
  }

  // Language options
  document.querySelectorAll(".lang-option").forEach(opt => {
    opt.addEventListener("click", () => setLanguage(opt.getAttribute("data-lang")));
  });

  // Mobile menu
  const menuBtn = document.querySelector(".menu-toggle");
  if (menuBtn) menuBtn.addEventListener("click", toggleMenu);

  // Close mobile menu on link click
  document.querySelectorAll(".nav a").forEach(a => {
    a.addEventListener("click", () => {
      const nav = document.querySelector(".nav");
      if (nav) nav.classList.remove("open");
    });
  });

  // Accordion
  initAccordion();

  // Set initial language
  setLanguage(currentLang);
});
